// @vitest-environment jsdom
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
const api=vi.hoisted(()=>({getIntegrationStatus:vi.fn(),updateIntegrationSettings:vi.fn(),getIntegrationClientConfig:vi.fn()}))
vi.mock('../../shared/tauri/commands',()=>api)
import { McpSettings } from './McpSettings'
const initial={enabled:false,running:false,port:43127,scopes:['notes:read','tasks:read','jottings:read'],revision:1,error:null,executable:'C:/CoolNote.exe'}
beforeEach(()=>{vi.clearAllMocks();api.getIntegrationStatus.mockResolvedValue(initial);Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:vi.fn().mockResolvedValue(undefined)}})})
afterEach(cleanup)
it('applies switches and permissions immediately using the latest revision',async()=>{
  api.updateIntegrationSettings.mockImplementation(async request=>({...initial,...request,running:request.enabled,revision:request.baseRevision+1}))
  render(<McpSettings/> )
  await waitFor(()=>expect((screen.getByRole('switch') as HTMLInputElement).disabled).toBe(false))
  expect(screen.queryByText('保存设置')).toBeNull()
  fireEvent.click(screen.getByRole('switch'))
  await screen.findByText('本机服务运行中')
  await waitFor(()=>expect((screen.getByLabelText('写入小记') as HTMLInputElement).disabled).toBe(false))
  fireEvent.click(screen.getByLabelText('写入小记'))
  await waitFor(()=>expect(api.updateIntegrationSettings).toHaveBeenLastCalledWith(expect.objectContaining({enabled:true,baseRevision:2,scopes:expect.arrayContaining(['jottings:read','jottings:write']),rotateToken:false})))
})
it('debounces port edits and automatically applies the final valid port',async()=>{
  api.updateIntegrationSettings.mockImplementation(async request=>({...initial,...request,revision:2}))
  render(<McpSettings/> )
  const port=screen.getByRole('spinbutton')
  await waitFor(()=>expect((port as HTMLInputElement).disabled).toBe(false))
  fireEvent.change(port,{target:{value:'432'}})
  fireEvent.change(port,{target:{value:'43210'}})
  expect(api.updateIntegrationSettings).not.toHaveBeenCalled()
  await waitFor(()=>expect(api.updateIntegrationSettings).toHaveBeenCalledWith(expect.objectContaining({port:43210,baseRevision:1})))
  expect(api.updateIntegrationSettings).toHaveBeenCalledTimes(1)
})
it('restores an invalid port without submitting it',async()=>{
  render(<McpSettings/> )
  const port=screen.getByRole('spinbutton')
  await waitFor(()=>expect((port as HTMLInputElement).disabled).toBe(false))
  fireEvent.change(port,{target:{value:'70000'}});fireEvent.blur(port)
  expect((port as HTMLInputElement).value).toBe('43127')
  expect(api.updateIntegrationSettings).not.toHaveBeenCalled()
  expect(screen.getByRole('alert').textContent).toContain('已恢复原值')
})
it('copies a client configuration without asking for a token',async()=>{
  api.getIntegrationStatus.mockResolvedValue({...initial,enabled:true,running:true})
  api.getIntegrationClientConfig.mockResolvedValue('[mcp_servers.coolnote]\ncommand = "CoolNote.exe"\nargs = ["--mcp"]')
  render(<McpSettings/> )
  await waitFor(()=>expect((screen.getByText('复制 Codex 配置') as HTMLButtonElement).disabled).toBe(false))
  fireEvent.click(screen.getByText('复制 Codex 配置'))
  await waitFor(()=>expect(navigator.clipboard.writeText).toHaveBeenCalledWith(expect.stringContaining('--mcp')))
  expect(api.getIntegrationClientConfig).toHaveBeenCalledWith('codex')
})
it('requires an explicit second click to rotate credentials',async()=>{
  api.updateIntegrationSettings.mockResolvedValue({...initial,revision:2})
  render(<McpSettings/> )
  await waitFor(()=>expect((screen.getByText('重置连接凭证') as HTMLButtonElement).disabled).toBe(false))
  fireEvent.click(screen.getByText('重置连接凭证'));expect(api.updateIntegrationSettings).not.toHaveBeenCalled()
  fireEvent.click(screen.getByText('确认重置连接凭证'))
  await waitFor(()=>expect(api.updateIntegrationSettings).toHaveBeenCalledWith(expect.objectContaining({rotateToken:true})))
})
it('shows activation failures without claiming the service is running',async()=>{
  api.updateIntegrationSettings.mockRejectedValue({message:'端口已被占用'})
  render(<McpSettings/> )
  await waitFor(()=>expect((screen.getByRole('switch') as HTMLInputElement).disabled).toBe(false))
  fireEvent.click(screen.getByRole('switch'))
  expect((await screen.findByRole('alert')).textContent).toBe('端口已被占用')
  expect(screen.queryByText('本机服务运行中')).toBeNull()
  expect((screen.getByRole('switch') as HTMLInputElement).checked).toBe(false)
})
